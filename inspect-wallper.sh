#!/bin/sh
set -eu
target="${1:-/Applications/Wallper.app}"
output="$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)/wallper-analysis"
executable="$target/Contents/MacOS/Wallper"
mkdir -p "$output/evidence" "$output/resources"
shasum -a 256 "$executable" > "$output/evidence/sha256.txt"
file "$executable" > "$output/evidence/file.txt"
plutil -convert json -o "$output/evidence/Info.json" "$target/Contents/Info.plist"
codesign -d --entitlements :- "$target" > "$output/evidence/entitlements.plist" 2> "$output/evidence/codesign.txt"
otool -arch arm64 -L "$executable" > "$output/evidence/libraries.txt"
otool -arch arm64 -l "$executable" > "$output/evidence/load-commands.txt"
otool -arch arm64 -ov "$executable" > "$output/evidence/objc-metadata.txt"
otool -arch arm64 -v -s __TEXT __objc_methname "$executable" > "$output/evidence/objc-selectors.txt"
nm -arch arm64 "$executable" | xcrun swift-demangle > "$output/evidence/symbols.txt"
strings -a -arch arm64 "$executable" > "$output/evidence/strings.txt"
xcrun llvm-objdump --macho --arch=arm64 --disassemble --symbolize-operands "$executable" > "$output/evidence/disassembly-arm64.txt"
cp "$target/Contents/Resources/entries.json" "$output/resources/entries.json"
cp "$target/Contents/Resources/mediaremote-adapter.pl" "$output/resources/mediaremote-adapter.pl"
printf 'Evidence saved to %s\n' "$output"
